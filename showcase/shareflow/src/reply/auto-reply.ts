/**
 * The auto-reply agent's deterministic half — a transcription of `ai_backend/app/agents/reply.py`.
 *
 * `/reply` is the last endpoint standing between this runtime and removing `ai_backend`, and it looked
 * like the hardest one to port until the Python was read: **almost none of it is a model call.** Rule
 * matching, confidence, escalation, lead detection, the language and style signals and every persona
 * instruction are keyword heuristics. Only the reply *text* goes through a model.
 *
 * So this file is the part that must be transcribed **exactly**, and it is separated from the model
 * call for that reason: it is testable without one, and the thresholds it produces decide whether a
 * reply is sent to a customer's audience without a human seeing it. `web/src/lib/ingest.ts` gates on
 * `confidence >= threshold`, so a score that drifts by 0.1 either auto-sends what a person should have
 * read or silently stops auto-sending anything. Nothing here is "improved" — where the Python's
 * behaviour is odd, the oddity is kept and noted.
 *
 * ## What `draft_comment_reply` is not
 *
 * There is already a tool of a similar name, and it is a different capability: it stores a draft
 * against an existing inbox comment for a person to approve. This classifies an *inbound* comment
 * against the workspace's rules and returns `{ reply, confidence, ruleTitle, escalate, lead }` for the
 * ingest cycle to act on. Conflating them was the reason `/reply` was recorded as having no successor.
 */

/** One active `bot_rules` row, as the ingest worker passes it. */
export type BotRule = {
  readonly title: string;
  readonly description?: string | null;
};

export type ReplyPersona = {
  readonly replyName?: string | null;
  readonly accountType: "personal" | "brand" | "business";
  readonly tone: "natural" | "friendly" | "professional" | "casual" | "witty";
  readonly replyLength: "short" | "balanced" | "detailed";
  readonly emojiPreference: "off" | "light" | "mirror";
  readonly mirrorCommenterLanguage: boolean;
  readonly mirrorCommenterStyle: boolean;
  readonly allowBrandMentions: boolean;
  readonly customInstructions?: string | null;
};

/** The Python's `ReplyPersona` field defaults, which a caller sending a partial persona relies on. */
export const DEFAULT_REPLY_PERSONA: ReplyPersona = {
  accountType: "personal",
  tone: "natural",
  replyLength: "short",
  emojiPreference: "mirror",
  mirrorCommenterLanguage: true,
  mirrorCommenterStyle: true,
  allowBrandMentions: false,
};

export type ReplyThreadMessage = {
  readonly role: "commenter" | "account";
  readonly content: string;
};

export type LeadDetection = {
  readonly isLead: boolean;
  readonly valueCents?: number | null;
  readonly reason?: string | null;
};

